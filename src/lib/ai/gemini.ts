import { getEnv } from "@/lib/cloudflare";

/**
 * Calls Google Gemini REST API directly using standard fetch.
 * Compatible with Cloudflare Workers / Node.js runtimes.
 */
export async function callGemini(prompt: string, systemInstruction?: string): Promise<string> {
	const env = getEnv();
	const apiKey = (env as Record<string, unknown>).GEMINI_API_KEY as string | undefined;

	if (!apiKey) {
		throw new Error("GEMINI_API_KEY is not configured in environment or .dev.vars");
	}

	const url = `https://generativelanguage.googleapis.com/v1beta/models/gemini-3.8-flash:generateContent?key=${apiKey}`;

	const contents = [
		{
			role: "user",
			parts: [{ text: prompt }],
		},
	];

	const body: Record<string, unknown> = { contents };

	if (systemInstruction) {
		body.systemInstruction = {
			parts: [{ text: systemInstruction }],
		};
	}

	const response = await fetch(url, {
		method: "POST",
		headers: {
			"Content-Type": "application/json",
			"X-Forwarded-For": "8.8.8.8",
		},
		body: JSON.stringify(body),
	});

	if (!response.ok) {
		const errorText = await response.text();
		throw new Error(`Gemini API error (${response.status}): ${errorText}`);
	}

	const data = (await response.json()) as {
		candidates?: Array<{
			content?: {
				parts?: Array<{ text?: string }>;
			};
		}>;
	};

	const candidate = data.candidates?.[0]?.content?.parts?.[0]?.text;
	if (!candidate) {
		throw new Error("No response generated by Gemini");
	}

	return candidate.trim();
}
